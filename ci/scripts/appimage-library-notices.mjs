#!/usr/bin/env node
// Writes the notices for everything linuxdeploy copied into the AppImage from the Ubuntu build machine,
// plus the pinned AppImage runtime and start-up files. See engineering/development/third-party-notices.md.

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { chmodSync, lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

export const NOTICES_PATH = 'usr/share/doc/macro-deck/THIRD-PARTY-NOTICES-LINUX-LIBRARIES';
export const HOST_TREE = 'usr/lib/Macro Deck/host';

// Reviewed against the LICENSE and build files at this commit. A different runtime needs a new review:
// the statically linked components and their versions below come from those files.
export const RUNTIME = {
	tag: '20251108',
	url: 'https://github.com/AppImage/type2-runtime/releases/download/20251108/runtime-x86_64',
	sha256: '2fca8b443c92510f1483a883f60061ad09b46b978b2631c807cd873a47ec260d',
	commit: 'dd6cebe',
	fullCommit: 'dd6cebedcbddde9c82f89b011e8e1d40b6e43868'
};

export const GENERATED_CACHES = ['loaders.cache', 'immodules.cache', 'gschemas.compiled'];

const APPRUN_BINARY_SHA256 = 'f30140a43a0a59e46db21bdefdf749b9e9f2c6946e92afabbacf98b8ae73fb4f';
const LINUXDEPLOY_APPRUN_MARKER = '# autogenerated by linuxdeploy';
const KNOWN_HOOKS = new Map([['linuxdeploy-plugin-gtk.sh', 'gtkHook']]);
const MERGED_USR_DIRS = ['bin', 'sbin', 'lib', 'lib32', 'lib64', 'libx32'];
const RULE = '-'.repeat(78);

export class NoticeError extends Error {}

export function parseRuntimeVersion(output) {
	const match = /AppImage runtime version: https:\/\/github\.com\/AppImage\/type2-runtime\/commit\/([0-9a-f]{7,40})\b/.exec(output);
	if (!match) {
		throw new NoticeError(`could not read the AppImage runtime version from: ${JSON.stringify(output.trim())}`);
	}
	return match[1];
}

export function assertRuntimeCommit(actual, source, expected = RUNTIME.commit) {
	if (actual !== expected) {
		throw new NoticeError(
			`${source} reports AppImage runtime commit ${actual}, but the reviewed runtime is ${expected}. ` +
				'Review the LICENSE and build files (src/runtime/Makefile, scripts/) of the new type2-runtime commit, ' +
				'then update RUNTIME and the runtime components in ci/scripts/appimage-library-notices.mjs.'
		);
	}
}

export function parseDesktopEntry(text) {
	const values = {};
	let inEntry = false;
	for (const line of text.split('\n')) {
		const trimmed = line.trim();
		if (trimmed.startsWith('[')) {
			inEntry = trimmed === '[Desktop Entry]';
			continue;
		}
		const eq = trimmed.indexOf('=');
		if (inEntry && eq > 0 && !(trimmed.slice(0, eq) in values)) {
			values[trimmed.slice(0, eq)] = trimmed.slice(eq + 1);
		}
	}
	const exec = values.Exec?.trim() ?? '';
	const binary = exec.startsWith('"') ? exec.slice(1, exec.indexOf('"', 1)) : exec.split(/\s+/)[0];
	return { binary: binary ? posix.basename(binary) : null, icon: values.Icon ?? null };
}

export function mergedUsrVariants(path) {
	const parts = path.split('/');
	if (parts[1] === 'usr' && MERGED_USR_DIRS.includes(parts[2])) {
		return [path, '/' + parts.slice(2).join('/')];
	}
	if (MERGED_USR_DIRS.includes(parts[1])) {
		return ['/usr' + path, path];
	}
	return [path];
}

export function systemCandidates(rel, multiarch) {
	const candidates = [...mergedUsrVariants('/' + rel)];
	const flat = /^usr\/lib\/([^/]+)$/.exec(rel);
	if (flat) {
		candidates.push(...mergedUsrVariants(`/usr/lib/${multiarch}/${flat[1]}`));
	}
	return [...new Set(candidates)];
}

export function parseDpkgSearch(stdout) {
	const entries = [];
	for (const line of stdout.split('\n')) {
		if (!line || line.startsWith('diversion by ')) {
			continue;
		}
		const sep = line.indexOf(': ');
		if (sep < 0) {
			continue;
		}
		entries.push({ packages: line.slice(0, sep).split(', ').map(p => p.trim()), path: line.slice(sep + 2) });
	}
	return entries;
}

export function classifyAppDir(entries, desktop) {
	const productName = desktop.fileName.replace(/\.desktop$/, '');
	const appOwned = new Set([
		desktop.fileName,
		`usr/share/applications/${desktop.fileName}`,
		`${productName}.png`,
		...(desktop.icon ? [`${desktop.icon}.png`, `${desktop.icon}.svg`] : []),
		...(desktop.binary ? [`usr/bin/${desktop.binary}`] : [])
	]);
	const iconPattern = desktop.icon ? new RegExp(`^usr/share/icons/hicolor/[^/]+/apps/${escapeRegExp(desktop.icon)}\\.(png|svg)$`) : null;

	const system = [];
	const tooling = [];
	const hostNames = new Set();
	for (const { rel, type } of entries) {
		if (type === 'file' && rel.startsWith(HOST_TREE + '/')) {
			hostNames.add(posix.basename(rel));
		}
		if (type !== 'file' || rel === NOTICES_PATH || rel.startsWith(HOST_TREE + '/')) {
			continue;
		}
		if (appOwned.has(rel) || iconPattern?.test(rel)) {
			continue;
		}
		if (rel === 'AppRun' || rel === 'AppRun.wrapped' || rel.startsWith('apprun-hooks/')) {
			tooling.push(rel);
			continue;
		}
		system.push(rel);
	}
	return { system: system.sort(), tooling: tooling.sort(), hostNames };
}

export function attributeFile(rel, { multiarch, system, dpkg, hostNames = new Set() }) {
	const name = posix.basename(rel);
	const realPaths = new Set();
	for (const candidate of systemCandidates(rel, multiarch)) {
		const real = system.realpath(candidate);
		if (real) {
			realPaths.add(real);
		}
	}
	if (realPaths.size === 0 && /^usr\/lib\/[^/]+$/.test(rel)) {
		for (const entry of dpkg.search(`*/${name}`)) {
			const real = posix.basename(entry.path) === name ? system.realpath(entry.path) : null;
			if (real) {
				realPaths.add(real);
			}
		}
	}
	if (realPaths.size === 0 && /^usr\/lib\/[^/]+$/.test(rel) && hostNames.has(name)) {
		return { kind: 'host', systemPaths: [] };
	}
	if (realPaths.size === 0) {
		throw new NoticeError(`${rel}: no file on this system matches it, so its Ubuntu package cannot be determined`);
	}

	const owners = new Set();
	for (const real of realPaths) {
		for (const variant of mergedUsrVariants(real)) {
			for (const entry of dpkg.search(variant)) {
				if (entry.path === variant) {
					entry.packages.forEach(p => owners.add(p));
				}
			}
		}
	}
	const systemPaths = [...realPaths].sort();
	if (owners.size === 1) {
		return { kind: 'package', package: [...owners][0], systemPaths };
	}
	if (owners.size === 0 && GENERATED_CACHES.includes(name)) {
		return { kind: 'generated', systemPaths };
	}
	if (owners.size === 0) {
		throw new NoticeError(`${rel}: no Ubuntu package owns ${systemPaths.join(' or ')}`);
	}
	throw new NoticeError(`${rel}: ambiguous, ${systemPaths.join(' and ')} belong to ${[...owners].sort().join(', ')}`);
}

export function identifyTooling(tooling, readAppDirFile) {
	const found = [];
	const problems = [];
	for (const rel of tooling) {
		const content = readAppDirFile(rel);
		if (rel.startsWith('apprun-hooks/')) {
			const key = KNOWN_HOOKS.get(rel.slice('apprun-hooks/'.length));
			key ? found.push({ key, rel }) : problems.push(`${rel}: unknown AppRun hook, review its origin and license`);
		} else if (sha256(content) === APPRUN_BINARY_SHA256) {
			found.push({ key: 'appRun', rel });
		} else if (content.toString('utf8').includes(LINUXDEPLOY_APPRUN_MARKER)) {
			found.push({ key: 'linuxdeployAppRun', rel });
		} else {
			problems.push(`${rel}: not the reviewed AppImageKit AppRun nor a linuxdeploy-generated AppRun, review its origin and license`);
		}
	}
	return { found, problems };
}

export function packageName(pkg) {
	return pkg.replace(/:[a-z0-9]+$/, '');
}

export function launchpadUrl(source, version) {
	return `https://launchpad.net/ubuntu/+source/${source}/${version}`;
}

export function renderNotices({ osName, packages, generated, hostCopies = [], tooling, lgplText }) {
	const out = [];
	out.push('Macro Deck for Linux (AppImage): bundled system libraries and tools', '='.repeat(68), '');
	out.push(
		`The AppImage bundles the libraries and data files listed below. They were copied from ${osName}`,
		'packages on the build machine and are distributed under the licenses stated in each package\'s',
		'copyright file, reproduced verbatim below. The notices for Macro Deck\'s own dependencies are',
		'listed separately, under Open source licenses in the application.',
		'',
		'Source code: each package below names the Ubuntu source package and version it was built from. The',
		'complete corresponding source code is available from the Ubuntu archive',
		'(https://archive.ubuntu.com/ubuntu/pool/), from Launchpad at the URL given for each package, and with',
		'apt-get source <source>=<version> on the same Ubuntu release with source repositories enabled.',
		''
	);

	out.push(RULE, '1. AppImage runtime', RULE, '');
	out.push(...renderRuntime(lgplText), '');

	out.push(RULE, '2. AppImage start-up files', RULE, '');
	for (const { key, rel } of tooling) {
		const entry = TOOLING[key];
		out.push(`${entry.title}`, `File: ${rel}`, `Source: ${entry.source}`, `License: ${entry.license}`, '', entry.text, '');
	}

	out.push(RULE, '3. Ubuntu packages', RULE, '');
	const printedCopyright = new Map();
	for (const pkg of packages) {
		const copyright = pkg.copyright.replace(/\s+$/, '');
		const sameAs = printedCopyright.get(copyright);
		printedCopyright.set(copyright, sameAs ?? pkg.name);
		out.push(
			`Package: ${pkg.name} ${pkg.version}`,
			`Source package: ${pkg.source} ${pkg.sourceVersion}`,
			`Source code: ${launchpadUrl(pkg.source, pkg.sourceVersion)}`,
			'Files:',
			...pkg.files.map(f => `  ${f}`),
			'',
			...(sameAs
				? [`Copyright file (/usr/share/doc/${pkg.name}/copyright): identical to the one of ${sameAs} above.`]
				: [`Copyright file (/usr/share/doc/${pkg.name}/copyright):`, '', copyright]),
			'',
			RULE,
			''
		);
	}

	out.push('4. Generated files', RULE, '');
	out.push('These caches were generated on the build machine from the files above and belong to no package:', '');
	out.push(...listOrNone(generated), '');
	out.push(RULE, '5. Copies of Macro Deck host files', RULE, '');
	out.push('linuxdeploy copied these libraries from the Macro Deck host; they are listed with its notices:', '');
	out.push(...listOrNone(hostCopies), '');
	return out.join('\n');
}

function listOrNone(files) {
	return files.length ? files.map(f => `  ${f}`) : ['  (none)'];
}

function renderRuntime(lgplText) {
	const source = `https://github.com/AppImage/type2-runtime/tree/${RUNTIME.fullCommit}`;
	const out = [
		`AppImage type 2 runtime, release ${RUNTIME.tag}, commit ${RUNTIME.commit}`,
		'The executable header of the AppImage file that mounts and starts the application.',
		`Release: https://github.com/AppImage/type2-runtime/releases/tag/${RUNTIME.tag}`,
		`Source code: ${source}`,
		'License: MIT, with the statically linked components below.',
		'',
		TYPE2_RUNTIME_LICENSE,
		''
	];
	for (const component of RUNTIME_COMPONENTS) {
		out.push(
			`${component.name} ${component.version}, statically linked into the runtime`,
			...(component.origin ? [`Built from: ${component.origin}`] : []),
			`License: ${component.license}`,
			`Source code: ${component.source}`,
			...(component.note ? [component.note] : []),
			'',
			component.text,
			''
		);
		if (component.lgpl) {
			out.push(`Full text of the GNU Lesser General Public License, version 2.1:`, '', lgplText.replace(/\s+$/, ''), '');
		}
	}
	return out;
}

export async function generateNotices(appDir, { multiarch, system, dpkg }) {
	const entries = listAppDir(appDir);
	const desktopFiles = entries.filter(e => !e.rel.includes('/') && e.rel.endsWith('.desktop'));
	if (desktopFiles.length !== 1) {
		throw new NoticeError(`expected exactly one desktop entry at the top of ${appDir}, found ${desktopFiles.length}`);
	}
	const desktop = {
		fileName: desktopFiles[0].rel,
		...parseDesktopEntry(readFileSync(join(appDir, desktopFiles[0].rel), 'utf8'))
	};
	const { system: systemFiles, tooling, hostNames } = classifyAppDir(entries, desktop);

	const problems = [];
	const byPackage = new Map();
	const generated = [];
	const hostCopies = [];
	for (const rel of systemFiles) {
		try {
			const result = attributeFile(rel, { multiarch, system, dpkg, hostNames });
			if (result.kind === 'host') {
				hostCopies.push(rel);
			} else if (result.kind === 'generated') {
				generated.push(rel);
			} else {
				const files = byPackage.get(result.package) ?? [];
				files.push(rel);
				byPackage.set(result.package, files);
			}
		} catch (error) {
			if (!(error instanceof NoticeError)) {
				throw error;
			}
			problems.push(error.message);
		}
	}

	const identified = identifyTooling(tooling, rel => readFileSync(join(appDir, rel)));
	problems.push(...identified.problems);

	const packages = [];
	for (const [pkg, files] of byPackage) {
		const info = dpkg.info(pkg);
		const name = packageName(pkg);
		const copyright = system.readFile(`/usr/share/doc/${name}/copyright`);
		if (!copyright) {
			problems.push(`${pkg}: /usr/share/doc/${name}/copyright is missing`);
			continue;
		}
		packages.push({ name, ...info, files: files.sort(), copyright });
	}
	packages.sort((a, b) => a.name.localeCompare(b.name));

	if (problems.length) {
		throw new NoticeError(`cannot attribute every bundled file:\n  ${problems.join('\n  ')}`);
	}

	const lgplText = system.readFile('/usr/share/common-licenses/LGPL-2.1');
	if (!lgplText) {
		throw new NoticeError('/usr/share/common-licenses/LGPL-2.1 is missing');
	}
	const osName = readOsName(system.readFile('/etc/os-release'));
	const text = renderNotices({ osName, packages, generated, hostCopies, tooling: identified.found, lgplText });
	return { text, packages, generated, hostCopies };
}

export function readOsName(osRelease) {
	const values = Object.fromEntries(
		(osRelease ?? '')
			.split('\n')
			.map(line => /^([A-Z_]+)=(.*)$/.exec(line))
			.filter(Boolean)
			.map(([, key, value]) => [key, value.replace(/^"(.*)"$/, '$1')])
	);
	if (values.ID !== 'ubuntu') {
		throw new NoticeError(`the AppImage must be built on Ubuntu, this system is ${values.ID ?? 'unknown'}`);
	}
	return values.PRETTY_NAME ?? `Ubuntu ${values.VERSION_ID}`;
}

export function listAppDir(appDir) {
	const entries = [];
	const walk = rel => {
		for (const name of readdirSync(join(appDir, rel)).sort()) {
			const childRel = rel ? `${rel}/${name}` : name;
			const stat = lstatSync(join(appDir, childRel));
			if (stat.isDirectory()) {
				walk(childRel);
			} else {
				entries.push({ rel: childRel, type: stat.isSymbolicLink() ? 'symlink' : stat.isFile() ? 'file' : 'other' });
			}
		}
	};
	walk('');
	return entries;
}

function sha256(buffer) {
	return createHash('sha256').update(buffer).digest('hex');
}

function escapeRegExp(text) {
	return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const hostSystem = {
	realpath(path) {
		try {
			return realpathSync(path);
		} catch {
			return null;
		}
	},
	readFile(path) {
		try {
			return readFileSync(path, 'utf8');
		} catch {
			return null;
		}
	}
};

const hostDpkg = {
	search(pattern) {
		const result = spawnSync('dpkg-query', ['-S', pattern], { encoding: 'utf8' });
		if (result.status === 0) {
			return parseDpkgSearch(result.stdout);
		}
		if (result.status === 1) {
			return [];
		}
		throw new Error(`dpkg-query -S ${pattern} failed: ${result.error?.message ?? result.stderr}`);
	},
	info(pkg) {
		const result = spawnSync('dpkg-query', ['-W', '-f', '${Version}\\t${source:Package}\\t${source:Version}', pkg], {
			encoding: 'utf8'
		});
		if (result.status !== 0) {
			throw new Error(`dpkg-query -W ${pkg} failed: ${result.error?.message ?? result.stderr}`);
		}
		const [version, source, sourceVersion] = result.stdout.split('\t');
		return { version, source, sourceVersion };
	}
};

function runtimeVersionOf(file) {
	const result = spawnSync(file, ['--appimage-version'], { encoding: 'utf8' });
	if (result.error) {
		throw new NoticeError(`cannot run ${file} --appimage-version: ${result.error.message}`);
	}
	return parseRuntimeVersion(`${result.stderr}\n${result.stdout}`);
}

async function fetchRuntime(dest) {
	const response = await fetch(RUNTIME.url);
	if (!response.ok) {
		throw new NoticeError(`downloading ${RUNTIME.url} failed: HTTP ${response.status}`);
	}
	const data = Buffer.from(await response.arrayBuffer());
	const actual = sha256(data);
	if (actual !== RUNTIME.sha256) {
		throw new NoticeError(`${RUNTIME.url} has sha256 ${actual}, expected ${RUNTIME.sha256}`);
	}
	writeFileSync(dest, data);
	chmodSync(dest, 0o755);
	assertRuntimeCommit(runtimeVersionOf(dest), dest);
}

const MULTIARCH = { x64: 'x86_64-linux-gnu', arm64: 'aarch64-linux-gnu' };
const USAGE = 'usage: appimage-library-notices.mjs generate <appDir> | fetch-runtime <dest> | check-runtime <executable>';

async function main([command, target]) {
	if (!target) {
		throw new NoticeError(USAGE);
	}
	switch (command) {
		case 'generate': {
			const { text, packages, generated, hostCopies } = await generateNotices(target, {
				multiarch: MULTIARCH[process.arch] ?? `${process.arch}-linux-gnu`,
				system: hostSystem,
				dpkg: hostDpkg
			});
			const output = join(target, NOTICES_PATH);
			mkdirSync(dirname(output), { recursive: true });
			writeFileSync(output, text);
			console.log(
				`Wrote ${NOTICES_PATH}: ${packages.length} package(s), ${generated.length} generated file(s), ` +
					`${hostCopies.length} host file copies`
			);
			for (const pkg of packages) {
				console.log(`  ${pkg.name} ${pkg.version} (${pkg.files.length} file(s))`);
			}
			return;
		}
		case 'fetch-runtime':
			await fetchRuntime(target);
			console.log(`Downloaded AppImage runtime ${RUNTIME.tag} (commit ${RUNTIME.commit}) to ${target}`);
			return;
		case 'check-runtime':
			assertRuntimeCommit(runtimeVersionOf(target), basename(target));
			console.log(`${basename(target)} carries AppImage runtime commit ${RUNTIME.commit}`);
			return;
		default:
			throw new NoticeError(USAGE);
	}
}

