#!/usr/bin/env node
// Renders the PKGBUILD for one AUR package from a published release. The
// matching .SRCINFO is derived from it by makepkg in publish-aur.yml.
//
// Usage: make-aur-package.mjs <pkgname> <version> <assetsJson> <sha256File> <outFile> [currentPkgbuild]
//   pkgname:         macro-deck-bin or macro-deck-beta-bin
//   version:         release version, e.g. 3.0.0-beta.3
//   assetsJson:      `gh release view --json assets` output, or the bare asset array
//   sha256File:      the release's *.deb.sha256 sidecar
//   outFile:         where to write the rendered PKGBUILD
//   currentPkgbuild: the PKGBUILD already in the AUR repository, for the pkgrel bump

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { normalizeAssetName, parseAssets } from './point-manifests-at-release.mjs';
import { mapNativePackageVersion, parseReleaseVersion } from './release-version.mjs';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TAURI_CONFIG = join(REPO_ROOT, 'ui', 'bootstrapper', 'tauri.conf.json');
const BOOTSTRAPPER_MANIFEST = join(REPO_ROOT, 'ui', 'bootstrapper', 'Cargo.toml');

export const STABLE_PACKAGE = 'macro-deck-bin';
export const BETA_PACKAGE = 'macro-deck-beta-bin';

export const ARCH_DEPENDS = [
  'gtk3',
  'webkit2gtk-4.1',
  'libayatana-appindicator',
  'xdotool',
  'gcc-libs',
  'zlib',
  'openssl',
  'icu',
  'shared-mime-info',
  'desktop-file-utils',
  'hicolor-icon-theme',
];

export function aurPackagesFor(version) {
  return parseReleaseVersion(version).isBeta ? [BETA_PACKAGE] : [STABLE_PACKAGE, BETA_PACKAGE];
}

// The AUR offers whatever was pushed last and ranks nothing, so nothing may
// replace a published package with an older version.
export function shouldPush({ pkgname, version, vercmp }) {
  return aurPackagesFor(version).includes(pkgname) && vercmp >= 0;
}

export function readPkgbuildField(text, field) {
  const match = new RegExp(`^${field}=(.*)$`, 'm').exec(text ?? '');
  return match === null ? null : match[1].trim();
}

// A packaging fix at an unchanged pkgver is invisible to an AUR helper unless
// pkgrel moves, and an unchanged re-render must not move it either.
export function nextPkgrel({ currentPkgbuild, renderedBody, currentBody, newPkgver }) {
  const currentPkgver = readPkgbuildField(currentPkgbuild, 'pkgver');
  if (currentPkgver !== newPkgver) {
    return 1;
  }
  if (renderedBody === currentBody) {
    return Number(readPkgbuildField(currentPkgbuild, 'pkgrel') ?? 1);
  }
  return Number(readPkgbuildField(currentPkgbuild, 'pkgrel') ?? 1) + 1;
}

export function parseChecksumSidecar(text) {
  const match = /^([0-9a-f]{64})\s+(.+?)\s*$/m.exec(text);
  if (match === null) {
    throw new Error('sidecar does not contain a "<sha256>  <name>" line');
  }
  return { sha256: match[1], stagedName: match[2] };
}

// GitHub sanitizes an asset name on upload, so the name the sidecar records is
// the pre-upload one and is never the name to download.
export function findReleaseAsset(assets, stagedName) {
  const wanted = normalizeAssetName(stagedName);
  for (const asset of assets) {
    const url = asset?.url ?? asset?.browser_download_url ?? asset?.browserDownloadUrl;
    if (typeof asset?.name === 'string' && typeof url === 'string' && normalizeAssetName(asset.name) === wanted) {
      return { name: asset.name, url };
    }
  }
  throw new Error(`the release carries no asset matching "${stagedName}"`);
}

export function maintainerFrom(cargoToml) {
  const match = /^authors\s*=\s*\[\s*"([^"]+)"/m.exec(cargoToml);
  if (match === null) {
    throw new Error('no authors entry found in the bootstrapper Cargo.toml');
  }
  return match[1];
}

export function renderPkgbuild(spec) {
  return `# Maintainer: ${spec.maintainer}
# Generated by ci/scripts/make-aur-package.mjs - do not edit by hand.

pkgname=${spec.pkgname}
pkgver=${spec.pkgver}
pkgrel=${spec.pkgrel}
pkgdesc="${spec.pkgdesc}${spec.pkgname === BETA_PACKAGE ? ' (prerelease)' : ''}"
arch=('x86_64')
url="${spec.url}"
license=('${spec.license}')
depends=(${ARCH_DEPENDS.map((name) => `'${name}'`).join(' ')})
provides=("macro-deck=$pkgver")
conflicts=('macro-deck')
options=('!strip' '!debug')
source=("${spec.assetName}::${spec.assetUrl}")
noextract=("${spec.assetName}")
sha256sums=('${spec.sha256}')

package() {
\tset -o pipefail
\tbsdtar -xOf "$srcdir/${spec.assetName}" 'data.tar.*' | bsdtar -xp -C "$pkgdir"
\t# makepkg runs package() without pipefail, so without the check above and the
\t# assertion below a failed extraction packages an empty tree and still exits 0.
\t[[ -f "$pkgdir/usr/bin/MacroDeck" ]]
}
`;
}

function main(argv) {
  const [pkgname, version, assetsFile, sha256File, outFile, currentPkgbuildFile] = argv;
  if (!pkgname || !version || !assetsFile || !sha256File || !outFile) {
    console.error(
      'usage: make-aur-package.mjs <pkgname> <version> <assetsJson> <sha256File> <outFile> [currentPkgbuild]',
    );
    process.exit(1);
  }

  const tauri = JSON.parse(readFileSync(TAURI_CONFIG, 'utf8'));
  const maintainer = maintainerFrom(readFileSync(BOOTSTRAPPER_MANIFEST, 'utf8'));
  const { sha256, stagedName } = parseChecksumSidecar(readFileSync(sha256File, 'utf8'));
  const asset = findReleaseAsset(parseAssets(readFileSync(assetsFile, 'utf8')), stagedName);
  const pkgver = mapNativePackageVersion(version).aurVersion;

  const currentPkgbuild = currentPkgbuildFile ? readFileSync(currentPkgbuildFile, 'utf8') : null;
  const spec = {
    pkgname,
    pkgver,
    pkgrel: 1,
    pkgdesc: tauri.bundle.shortDescription,
    url: tauri.bundle.homepage,
    license: tauri.bundle.license,
    maintainer,
    assetName: asset.name,
    assetUrl: asset.url,
    sha256,
  };

  const withoutPkgrel = (text) => text.replace(/^pkgrel=.*$/m, '');
  const rendered = renderPkgbuild(spec);
  spec.pkgrel = nextPkgrel({
    currentPkgbuild,
    renderedBody: withoutPkgrel(rendered),
    currentBody: currentPkgbuild === null ? null : withoutPkgrel(currentPkgbuild),
    newPkgver: pkgver,
  });

  writeFileSync(outFile, renderPkgbuild(spec));
  console.log(`${pkgname} ${pkgver}-${spec.pkgrel} -> ${asset.name}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
